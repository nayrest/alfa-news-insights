const insightId = (companyId: string, eventKey: string) => `${companyId}__${eventKey}`;

function build(companyId: string, it: Interpretation): Insight {
  const ev = EVENTS[it.event];
  const company = mockCompanies.find((c) => c.id === companyId);
  const id = insightId(companyId, it.event);
  return {
    id,
    news_id: id,
    company_id: companyId,
    status: 'ok',
    title: ev.title,
    lead: it.lead,
    what_happened: ev.facts.map((f) => f.text).join(' '),
    kind: it.kind,
    category: ev.category,
    relevance: it.relevance,
    horizon: 'квартал',
    published_at: ev.published_at,
    facts: ev.facts,
    bank_view: ev.bank_view,
    ai: {
      why_important: it.why,
      inferences: [],
      consequences: it.consequences,
      actions: it.actions,
      questions: [],
      product_hint: null,
    },
    company_factors: it.factors,
    feature_labels: {},
    sources: ev.sources,
    trace: [
      { step: 'Планирование', tool: 'planner', detail: `Цель: оценить влияние события «${ev.title}» на ${company?.name ?? companyId}.` },
      { step: 'Профиль клиента', tool: 'get_company_profile', detail: `Загружены признаки: ОКВЭД ${company?.okved_code}, продукты банка, ВЭД, группа компаний.` },
      { step: 'Поиск новостей', tool: 'search_news', detail: `Найдено подтверждений факта: ${ev.facts.length}.` },
      { step: 'Аналитика банка', tool: 'rag_bank_analytics', detail: `Найдены материалы: ${ev.sources.filter((s) => s.type === 'bank_analytics').map((s) => `«${s.title}»`).join(', ')}.` },
      { step: 'Ранжирование', tool: 'score_relevance', detail: `Релевантность для клиента: ${Math.round(it.relevance * 100)}%.` },
      { step: 'Самопроверка', tool: 'verify_claims', detail: 'Каждый факт привязан к источнику, выводы модели отделены от позиции банка.' },
    ],
  };
}

const ALL: Insight[] = Object.entries(INTERPRETATIONS).flatMap(([companyId, list]) => list.map((it) => build(companyId, it)));

export function mockFeed(companyId: string): FeedItem[] {
  return ALL.filter((i) => i.company_id === companyId)
    .sort((a, b) => b.relevance - a.relevance)
    .map((i) => ({
      id: i.id,
      company_id: i.company_id,
      title: i.title,
      lead: i.lead,
      kind: i.kind,
      category: i.category,
      relevance: i.relevance,
      published_at: i.published_at,
      publisher: i.sources[0].publisher,
      why_selected: i.company_factors.map((f) => `${f.label}: ${f.value}`),
      insight_id: i.id,
    }));
}

export function mockInsight(id: string): Insight {
  const found = ALL.find((i) => i.id === id);
  if (!found) throw new Error(`Инсайт ${id} не найден`);
  return found;
}

export function mockAsk(id: string, question: string): ChatMessage {
  const insight = mockInsight(id);
  const bankSource = insight.sources.find((s) => s.type === 'bank_analytics');
  return {
    role: 'assistant',
    text:
      `Демо-ответ на вопрос «${question}». ${insight.ai.why_important} ` +
      `Первый шаг: ${insight.ai.actions[0].charAt(0).toLowerCase()}${insight.ai.actions[0].slice(1)}.`,
    source_ids: bankSource ? [bankSource.id] : [],
  };
}
