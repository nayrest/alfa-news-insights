def _compile(d: dict[str, list[str]]) -> dict[str, re.Pattern]:
    return {k: re.compile("|".join(v), re.IGNORECASE) for k, v in d.items()}


_TOPICS_RE = _compile(TOPICS)
_SECTORS_RE = _compile(SECTORS)
_COUNTRIES_RE = _compile(COUNTRIES)


def classify(title: str, summary: str = "") -> dict:
    text = f"{title}. {summary}".lower().replace("ё", "е")
    return {
        "topics": sorted(k for k, rx in _TOPICS_RE.items() if rx.search(text)),
        "sectors": sorted(k for k, rx in _SECTORS_RE.items() if rx.search(text)),
        "countries": sorted(k for k, rx in _COUNTRIES_RE.items() if rx.search(text)),
    }
